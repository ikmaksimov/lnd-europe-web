/**
 * Trencadís Icons — the shared icon module.
 * --------------------------------------------------------------------------
 * Blocks import their icons from here instead of inlining SVG paths, so the
 * whole library restyles from one file. This is a sidecar module copied into a
 * client project by `trencadis add` (like `lib/animations` and
 * `lib/edit-schema`) — deliberately NOT an npm dependency, which would break a
 * block's autonomy and force the CLI to touch the client's package.json.
 *
 * Style: **Phosphor duotone** (MIT — copying path data is licensed).
 *  - Phosphor geometry lives in a `0 0 256 256` viewBox, NOT Lucide's 24-box.
 *  - A duotone icon is two layers, both `currentColor`: a "ghost" shape at
 *    opacity 0.2 plus the main shape. Icons therefore inherit the surrounding
 *    `text-*` token colour and work unchanged inside a `theme-dark` scope.
 *  - Brand logos are single-colour fills — a two-tone brand mark reads wrong.
 *
 * Icons are decorative in this library (labels are always real text), so they
 * are `aria-hidden` by default. `size` and `className` pass through, so blocks
 * keep controlling scale and colour.
 *
 * Set (Phosphor name → export):
 *   caret-down → CaretDown · plus → Plus · x → X · list → List
 *   arrow-right → ArrowRight · arrow-up-right → ArrowUpRight
 *   arrow-circle-right → ArrowCircleRight · check → Check
 *   seal-check → SealCheck · drop → Drop · leaf → Leaf · sun → Sun
 *   shield → Shield · wrench → Wrench · key → Key · sparkle → Sparkle
 *   tag → Tag · envelope → Envelope · file-text → FileText · clock → Clock
 *   house → House · credit-card → CreditCard · truck → Truck · globe → Globe
 *   cpu → Cpu · star → Star
 *   instagram-logo → InstagramLogo · facebook-logo → FacebookLogo
 *   linkedin-logo → LinkedinLogo   (all three: `fill` variant, single colour)
 * Plus `BrandMark`, the trencadís tile placeholder logo — not a Phosphor icon,
 * so it keeps its own geometry and 24-box.
 */
import type { ReactNode, SVGProps } from 'react';

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'children'> {
  /** Rendered width and height. Blocks pass the size the layout needs. */
  size?: number | string;
}

/** Shared <svg> shell: Phosphor's 256 viewBox, currentColor, decorative. */
function Icon({ size = 24, children, ...rest }: IconProps & { children: ReactNode }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 256 256"
      fill="currentColor"
      aria-hidden="true"
      {...rest}
    >
      {children}
    </svg>
  );
}

